// the selected button is drawn inverted: same shape, black and white swapped
void drawWord(int16_t x, int16_t y, byte item, bool inverted)
{
  if (!inverted) { sprites.drawPlusMask(x, y, menuWords, item); return; }
  const unsigned char *d = menuWords + 2 + (uint16_t)item * 60;
  for (byte c = 0; c < 30; c++)
  {
    byte img = pgm_read_byte(d++), mask = pgm_read_byte(d++);
    for (byte r = 0; r < 8; r++)
      if (mask & (1 << r)) arduboy.drawPixel(x + c, y + r, (img & (1 << r)) ? BLACK : WHITE);
  }
}

void drawMenu()
{
  for (byte i = 0; i < 4; i++) drawWord(1 + i * 32, MENU_Y, i, i == menuSelection);
}

// the world that scrolls by behind the title (no chicken)
bool    titleReady = false;
byte    titleSub = 0;

void titleWorld()
{
  scrollY = -32000;                                     // no dead zone behind the title screen
  if (!titleReady || (camY >> 3) > 3000)                // (re)build the world; also before the rows get too big for int16
  {
    worldInit();
    player.set();
    player.characteristics = 0;                         // no chicken
    camX = player.x; camY = player.y;
    titleSub = 0;
    titleReady = true;
  }
  titleSub += 6;                                        // 6/16 px per frame
  camY += titleSub >> 4;
  titleSub &= 15;
  int16_t cr = camY >> 3;
  extendWorld(cr);
  updateLanes(cr);
  drawGround();
  drawObjects();
}

void drawTitle()
{
  if (menuSelection > 3) menuSelection = 1;             // PLAY is pre-selected
  titleWorld();
  drawLogo();
  drawMenu();
}

